// Export the theme and a function to toggle between light and dark mode
export { theme };

// Function to toggle between light and dark mode
export const toggleColorMode = (currentTheme: Theme): Theme => {
  const newMode = currentTheme.palette.mode === 'light' ? 'dark' : 'light';
  
  // Save the new theme preference to localStorage
  localStorage.setItem(process.env.REACT_APP_THEME_STORAGE_KEY || 'tata_commerce_theme', newMode);
  
  // Create and return the new theme
  return responsiveFontSizes(createTheme(getThemeOptions(newMode)));
};