// Get the user's preferred color scheme from localStorage or system preference
const getPreferredColorScheme = (): PaletteMode => {
  const storedTheme = localStorage.getItem(process.env.REACT_APP_THEME_STORAGE_KEY || 'tata_commerce_theme');
  
  if (storedTheme) {
    return storedTheme as PaletteMode;
  }
  
  // Check if the user's system preference is dark mode
  if (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches) {
    return 'dark';
  }
  
  // Default to light mode
  return 'light';
};

